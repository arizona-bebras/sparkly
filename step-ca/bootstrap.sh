#!/bin/bash
set -euo pipefail
umask 077

export STEPPATH=/home/step
config="$STEPPATH/config/ca.json"
credentials="$STEPPATH/sparkly"
export_dir=/run/device-pki

# Initialize in a staging directory, so an interrupted first boot is retryable.
if [ ! -f "$config" ]; then
    staging=$(mktemp -d "$STEPPATH/.init.XXXXXX")
    trap 'rm -rf "$staging"' EXIT
    mkdir -p "$staging/secrets"
    step crypto rand 64 > "$staging/secrets/password"
    STEPPATH="$staging" step ca init \
        --deployment-type standalone \
        --name "${STEP_CA_NAME:-Sparkly Device CA}" \
        --dns "${STEP_CA_DNS_NAMES:-step-ca,localhost,host.docker.internal}" \
        --address :9000 --provisioner bootstrap-admin \
        --password-file "$staging/secrets/password"

    # Set CA lifetimes only during initial provisioning, before any certificates
    # are issued or trust roots exported. Retain the keys generated by ca init.
    step certificate create "${STEP_CA_NAME:-Sparkly Device CA} Root CA" \
        "$staging/certs/root_ca.crt" --profile root-ca \
        --key "$staging/secrets/root_ca_key" \
        --password-file "$staging/secrets/password" \
        --not-after 87600h --force
    step certificate create "${STEP_CA_NAME:-Sparkly Device CA} Intermediate CA" \
        "$staging/certs/intermediate_ca.crt" --profile intermediate-ca \
        --key "$staging/secrets/intermediate_ca_key" \
        --password-file "$staging/secrets/password" \
        --ca "$staging/certs/root_ca.crt" \
        --ca-key "$staging/secrets/root_ca_key" \
        --ca-password-file "$staging/secrets/password" \
        --not-after 43800h --force

    # Store final paths before moving the generated configuration into place.
    jq --arg staging "$staging" --arg final "$STEPPATH" \
        'walk(if type == "string" then sub($staging; $final) else . end)' \
        "$staging/config/ca.json" > "$staging/config/ca.json.tmp"
    mv "$staging/config/ca.json.tmp" "$staging/config/ca.json"
    for directory in certs secrets db; do
        if [ -d "$staging/$directory" ]; then
            mkdir -p "$STEPPATH/$directory"
            cp -R "$staging/$directory/." "$STEPPATH/$directory/"
        fi
    done
    mkdir -p "$STEPPATH/config"
    cp "$staging/config/ca.json" "$config"
    rm -rf "$staging"
    trap - EXIT
fi

mkdir -p "$credentials"
# Generate the JWK and PEM together before atomically installing the directory.
if [ ! -d "$credentials/provisioner" ]; then
    temporary=$(mktemp -d "$credentials/.provisioner.XXXXXX")
    trap 'rm -rf "$temporary"' EXIT
    step crypto jwk create "$temporary/public.json" "$temporary/private.json" \
        --kty EC --crv P-256 --no-password --insecure
    step crypto key format "$temporary/private.json" --pem --no-password --insecure \
        --out "$temporary/key.pem"
    mv "$temporary" "$credentials/provisioner"
    trap - EXIT
fi

# Update the dedicated provisioner on startup, including template changes.
# This CA is dedicated to Sparkly devices; no generic bootstrap provisioner remains.
jq --slurpfile key "$credentials/provisioner/public.json" \
    --rawfile template /opt/sparkly/device.tpl '
    .authority.provisioners = [{
        type: "JWK", name: "sparkly-devices", key: $key[0],
        claims: {minTLSCertDuration: "5m", defaultTLSCertDuration: "8760h", maxTLSCertDuration: "8760h"},
        options: {x509: {template: $template}}
    }]
' "$config" > "$config.tmp"
mv "$config.tmp" "$config"

# Readable by the distroless backend's nonroot user; volume mounted read-only there.
# This volume contains no root/intermediate CA private keys or CA unlock password.
chmod 755 "$export_dir"
cp "$STEPPATH/certs/root_ca.crt" "$export_dir/root_ca.crt.tmp"
cp "$credentials/provisioner/key.pem" "$export_dir/provisioner.key.tmp"
jq -er .kid "$credentials/provisioner/public.json" > "$export_dir/provisioner.kid.tmp"
for name in root_ca.crt provisioner.key provisioner.kid; do
    chmod 444 "$export_dir/$name.tmp"
    mv "$export_dir/$name.tmp" "$export_dir/$name"
done

# Local gateway server credentials are separate from the backend's issuance key.
# Kubernetes can supply the same files from cert-manager-managed Secrets instead.
gateway=$(mktemp -d "$credentials/.gateway.XXXXXX")
trap 'rm -rf "$gateway"' EXIT
step certificate create envoy "$gateway/server.crt" "$gateway/server.key" \
    --template /opt/sparkly/envoy-server.tpl \
    --san envoy --san localhost --san host.docker.internal --san 127.0.0.1 \
    --ca "$STEPPATH/certs/intermediate_ca.crt" \
    --ca-key "$STEPPATH/secrets/intermediate_ca_key" \
    --ca-password-file "$STEPPATH/secrets/password" \
    --not-after 720h --no-password --insecure
chmod 755 /run/envoy-pki
# Replace read-only exports through temporary files, including after interrupted startup.
rm -f /run/envoy-pki/server-chain.crt.tmp /run/envoy-pki/server.key.tmp /run/envoy-pki/root_ca.crt.tmp
cat "$gateway/server.crt" "$STEPPATH/certs/intermediate_ca.crt" > /run/envoy-pki/server-chain.crt.tmp
cp "$gateway/server.key" /run/envoy-pki/server.key.tmp
cp "$STEPPATH/certs/root_ca.crt" /run/envoy-pki/root_ca.crt.tmp
for name in server-chain.crt server.key root_ca.crt; do
    chmod 444 "/run/envoy-pki/$name.tmp"
    mv "/run/envoy-pki/$name.tmp" "/run/envoy-pki/$name"
done
rm -rf "$gateway"
trap - EXIT

exec step-ca --password-file "$STEPPATH/secrets/password" "$config"
